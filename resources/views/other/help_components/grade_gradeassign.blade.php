
<p class="answer">
    The grade assignment page is accessable from the "Grade" tab. Gradeomatic automatically calculates the maximum
    possible score on the exam, along with suggestions for letter grades. If you don't want to use a letter, simply
    empty the box and it will not be a possible grade for students. The charts on the right-hand side of the page
    show a histogram of the number of students currently receiving each grade and a barchart showing exam scores for
    each student ordered from low to high, along with their grade.
</p>