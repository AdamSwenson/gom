<p class="answer">Each exam has a student roster with all the students who will take the exam. On the "edit roster"
    page you can import students from a .csv file and edit student information.</p>

<p class="answer">The only required information is the first and last name of the student. You may also include the
    student's ID number (if, for example, you wish to grade the exams blindly) and their email address if you want
    to have a link for accessing feedback emailed directly to the students.</p>

<p class="answer">Pressing "Save & Exit" will save any changes to the roster. Note that any changes you make will
    only be saved by pressing "Save & Exit"</p>
