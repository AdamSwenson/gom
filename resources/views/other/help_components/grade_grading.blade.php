
<p class="answer">
    To grade an exam, select the exam from the "Grade" tab and pick a student. This will reveal the questions for
    the exam and a slider for each element. For each element, move the slider to a value that corresponds to the
    student's performance. This won't affect the question grade, but it will affect the written feedback.
    If you wish to tailor the student's feedback individually, simply modify the text box next to that element.
    Enter a score for the question, then move to the next question. Once a grade is entered for a student, the exam
    is considered graded for timing and release purposes. This allows you to construct exams where students may
    choose among one or more questions to answer. If the student didn't need to answer a question, simply leave the
    score area blank and they won't be graded.
</p>