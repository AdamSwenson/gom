
<h4>What elements are and what they do</h4>

<p class="answer"><i>Elements</i> can be a bit tricky to explain since they have multiple roles and are very
    flexible. On their most basic use, elements have three jobs:</p>
<ol>
    <li>Elements comprise questions</li>
    <li>Elements form the basis of feedback</li>
    <li>Elements let you compare student performance across different exams</li>
</ol>

<p class="answer">Elements comprise questions. On more complex questions, where you are asking the student to do
    multiple things or where explaining a concept requires several different components, each task or component
    should be represented by an element. </p>

<p class="answer">Multi-part questions or short essays spanning several paragraphs might have several elements.
    While a short-form question might only have one. A question can have zero elements if you only want to use the
    gradeomatic for reporting scores.
</p>

<p class="answer">If you are familiar with using rubrics to grade an exam, you are already familiar with how to
    divide a question into its elements. For those who are less familiar, here is one strategy you might try:</p>
<blockquote>
    Imagine that a good student comes to your office, distraught after doing poorly on one question on the exam. She
    asks 'What did I miss? What should I have done?' You'll probably say something like 'Well, you needed to do x,
    y, and z. You did a good job on x. But you totally forgot to bring up y. And there were several mistakes in your
    explanation of z'. When you have that conversation in your head, whatever you fill in for x, y, and z are the
    elements of the question
</blockquote>

<h4>Creating elements and comments</h4>

<p class="answer">On the "create & edit elements" page, you, um, create and edit elements. To do this, you provide a
    short name for the element which which will be meaningful to you when you see it during grading and in
    charts.</p>

<p class="answer">You then also provide some text that will form the basis for all feedback that you give on the
    element. to can provide a short name for the element along with a stock comment.
    In "element response", enter the basic description of what the student should do to fully answer the
    element.
    Pressing the "Customize Response" button allows you to take it
    one step further. Here you modify that basic comment to tailor it based on the student's performance. By
    default, gradeomatic allows for four responses varieties: "missing", "poor", "fair" and "excellent". These
    responses will be what the student sees once you have graded the exam.
</p>
